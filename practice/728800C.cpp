const int MOD = 107;
void solve(int cs) {
    int a, b; cin >> a >> b;
    auto pw = [](int a, int b) -> int {
        int ret = 1;
        while (b) {
            if (b & 1) ret = ret * a % MOD;
            a = a * a % MOD;
            b >>= 1;
        }
        return ret;
    };
    cout << pw(a, b) << endl;
}
